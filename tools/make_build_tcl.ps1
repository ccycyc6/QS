# Regenerate tools/build_full.tcl from the PDS project file.
# The GUI project is not used directly because it records a 2022.2 synthesiser path.
$ErrorActionPreference = 'Stop'

$here = $PSScriptRoot
$fpga = (Resolve-Path (Join-Path $here '..\fpga')).Path
$prj  = Join-Path $fpga 'prj_pds'
$pds  = Join-Path $prj  'hdmi_loop.pds'
$out  = Join-Path $here 'build_full.tcl'

$files = New-Object System.Collections.ArrayList
$ips   = New-Object System.Collections.ArrayList

foreach ($line in (Get-Content $pds)) {
    if ($line -match '\(_file "([^"]+)"') {
        $p = $Matches[1]
        if ($p -match '\.(sv|v)$') { [void]$files.Add($p) }
    }
    if ($line -match '\(_ip "([^"]+)"') { [void]$ips.Add($Matches[1]) }
}

$root = $fpga.Replace('\', '/')
$t = New-Object System.Collections.ArrayList
[void]$t.Add('# AUTO-GENERATED by tools/make_build_tcl.ps1 - do not edit by hand')
[void]$t.Add('set_arch -family Logos2 -device PG2L200H -speedgrade -6 -package FBB676')
[void]$t.Add('add_constraint {' + $root + '/prj_pds/hdmi_loop.fdc}')
foreach ($f in ($files | Select-Object -Unique)) { [void]$t.Add('add_design {' + $root + '/prj_pds/' + $f + '}') }
foreach ($f in ($ips   | Select-Object -Unique)) { [void]$t.Add('add_design {' + $root + '/prj_pds/' + $f + '}') }
[void]$t.Add('compile -top_module {hdmi_loop} -system_verilog -include_path [list {' + $root + '/rtl_pds} {' + $root + '/rtl_pds/data_process}]')
[void]$t.Add('synthesize -ads')
[void]$t.Add('dev_map')
[void]$t.Add('pnr')
[void]$t.Add('report_timing -max_path 20')
[void]$t.Add('report_power')
[void]$t.Add('gen_bit_stream -create_bit true')
[void]$t.Add('puts {=== BUILD_DONE ===}')
[void]$t.Add('exit')

[IO.File]::WriteAllText($out, ($t -join [Environment]::NewLine))
'wrote ' + $out
'  rtl files: ' + ($files | Select-Object -Unique).Count
'  ip  files: ' + ($ips   | Select-Object -Unique).Count
