# Generate tools/build_rv.tcl: vision RTL + ARES core + rv_top, WITH_RV enabled.
$ErrorActionPreference = 'Stop'

$here = $PSScriptRoot
$fpga = (Resolve-Path (Join-Path $here '..\fpga')).Path
$prj  = Join-Path $fpga 'prj_pds'
$pds  = Join-Path $prj  'hdmi_loop.pds'
$out  = Join-Path $here 'build_rv.tcl'

$files = New-Object System.Collections.ArrayList
$ips   = New-Object System.Collections.ArrayList
foreach ($line in (Get-Content $pds)) {
    if ($line -match '\(_file "([^"]+)"') { $p = $Matches[1]; if ($p -match '\.(sv|v)$') { [void]$files.Add((Join-Path $prj $p)) } }
    if ($line -match '\(_ip "([^"]+)"')   { [void]$ips.Add((Join-Path $prj $Matches[1])) }
}

# ARES source list (paths in the .f are relative to the ARES repo root)
$aresRoot = Join-Path $fpga 'ares'          # .f paths are relative to the ARES repo root
$fv = Join-Path $aresRoot 'rtl\pipeline\pipeline_pango.f'
foreach ($line in (Get-Content $fv)) {
    $l = $line.Trim()
    if ($l -eq '' -or $l.StartsWith('#') -or $l.StartsWith('+incdir+')) { continue }
    [void]$files.Add((Join-Path $aresRoot $l))
}
[void]$files.Add((Join-Path $fpga 'rtl_rv\rv_top.v'))

$root = $fpga.Replace('\', '/')
$t = New-Object System.Collections.ArrayList
[void]$t.Add('# AUTO-GENERATED by tools/make_build_rv_tcl.ps1 - vision + RISC-V core')
[void]$t.Add('set_arch -family Logos2 -device PG2L200H -speedgrade -6 -package FBB676')
[void]$t.Add('add_constraint {' + $root + '/prj_pds/hdmi_loop.fdc}')
foreach ($f in ($files | Select-Object -Unique)) { [void]$t.Add('add_design {' + $f.Replace('\','/') + '}') }
foreach ($f in ($ips   | Select-Object -Unique)) { [void]$t.Add('add_design {' + $f.Replace('\','/') + '}') }
$inc = @(
    ($root + '/rtl_rv/cfg_on'),
    ($root + '/rtl_pds'),
    ($root + '/rtl_pds/data_process'),
    ($root + '/ares/rtl/pipeline/include'),
    ($root + '/ares/rtl/pipeline/core/vsrc/include')
) | ForEach-Object { '{' + $_ + '}' }
[void]$t.Add('compile -top_module {hdmi_loop} -system_verilog -include_path [list ' + ($inc -join ' ') + ']')
[void]$t.Add('synthesize -ads')
[void]$t.Add('dev_map')
[void]$t.Add('puts {=== BUILD_RV_DONE ===}')
[void]$t.Add('exit')

[IO.File]::WriteAllText($out, ($t -join [Environment]::NewLine))
'wrote ' + $out
'  files: ' + ($files | Select-Object -Unique).Count + ', ip: ' + ($ips | Select-Object -Unique).Count
